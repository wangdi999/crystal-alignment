"""离线打开实际单文件，用鼠标、键盘和触屏验证全部关卡及存档。"""
import json,sys
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
local=ROOT/'.test-tools'
if local.exists():sys.path.insert(0,str(local))
from playwright.sync_api import sync_playwright
FILE=ROOT/'dist/crystal-alignment.html'
URL=FILE.as_uri()+'?mode=classic'
passed=[];errors=[]
def check(value,name):
    assert value,name
    passed.append(name);print('通过：'+name,flush=True)
def board(page):return page.locator('#board').evaluate('(b)=>({player:b.dataset.player,crates:b.dataset.crates})')
with sync_playwright() as pw:
    browser=pw.chromium.launch(executable_path=r'C:\Program Files\Google\Chrome\Application\chrome.exe',headless=True)
    context=browser.new_context(viewport={'width':1440,'height':1050},accept_downloads=True)
    context.set_offline(True)
    page=context.new_page()
    page.on('pageerror',lambda error:errors.append(str(error)))
    page.on('console',lambda msg:errors.append(msg.text) if msg.type=='error' else None)
    def level(i):page.locator(f'[data-level="{i}"]').click()
    def key(direction):page.keyboard.press({'up':'ArrowUp','right':'ArrowRight','down':'ArrowDown','left':'ArrowLeft'}[direction])
    page.goto(URL);page.wait_for_load_state('load')
    check(page.locator('#levels button').count()==6,'离线单文件加载六关，无外部资源依赖')
    page.screenshot(path=str(ROOT/'artifacts/01-desktop.png'),full_page=True)
    key('up');check(page.locator('#moves').inner_text()=='0','碰墙不计步')
    level(1);key('down');before=board(page)
    page.reload();check(board(page)==before and page.locator('#moves').inner_text()=='1','刷新恢复局内位置与推动计数')
    page.locator('#undo').click();check(page.locator('#moves').inner_text()=='0','刷新后可继续撤销')
    page.reload();page.locator('#redo').click();check(board(page)==before,'重做栈可存档并恢复同一步')
    level(3);key('left');level(1);check(board(page)==before,'切换关卡后恢复各自进度')
    page.locator('#restart').click();check(page.locator('#moves').inner_text()=='0' and page.locator('#redo').is_disabled(),'重开重置棋盘并清除重做栈')
    key('down');page.locator('#undo').click();key('left');check(page.locator('#redo').is_disabled(),'撤销后走新分支会清除重做')
    page.locator('#restart').click()
    for direction in ['down','right','down','left']:key(direction)
    check(page.locator('.cell.dead').count()>0 and '死位' in page.locator('#notice').inner_text(),'死局标识与可撤销提示')
    page.locator('#hint').click();check('无法归位' in page.locator('#notice').inner_text(),'死局提示不会误导自动前进')
    page.locator('#undo').click();check(page.locator('.cell.dead').count()==0,'撤销解除死局')
    page.locator('#restart').click();page.locator('#hint').click()
    check(page.locator('.hint-arrow').count()==1 and page.locator('#moves').inner_text()=='0','一步提示只指方向、不代为移动')
    with page.expect_download() as info:page.locator('#export').click()
    info.value.save_as(str(ROOT/'artifacts/partial-export.json'))
    check(json.loads((ROOT/'artifacts/partial-export.json').read_text(encoding='utf-8'))['sessions']['2']['stats']['hints']>=1,'导出包含提示与局内状态')
    for i in range(6):
        level(i);page.locator('#restart').click()
        if i==2:page.locator('#hint').click()
        solution=page.evaluate('(i)=>Crystal.solve(Crystal.load(Crystal.LEVELS[i]))',i)
        for direction in solution:key(direction)
        check(page.get_by_role('dialog').count()==1 and page.locator('#moves').inner_text()==str(len(solution)),f'第 {i+1} 关通过真实键盘操作通关')
        if i==2:check('借助提示' in page.locator('.badge').inner_text(),'借助提示与独立最优解分别标记')
        if i==5:
            check('全部共鸣' in page.locator('#win-title').inner_text(),'全部六关完成时显示总通关结果')
            page.screenshot(path=str(ROOT/'artifacts/02-complete.png'),full_page=True)
        page.keyboard.press('Shift+Tab');check(page.locator('#review').evaluate('(b)=>b===document.activeElement'),'通关弹窗键盘焦点循环')
        page.get_by_role('button',name='查看棋盘',exact=True).click()
    page.reload();check(page.locator('#progress').inner_text()=='6 / 6 完成','完成记录刷新后保留')
    level(4);page.locator('#undo').click();check(page.locator('#moves').inner_text()=='21','通关后仍可撤销复盘')
    page.locator('#redo').click();check(page.get_by_role('dialog').count()==1,'重做最后一步重新通关')
    page.get_by_role('button',name='查看棋盘',exact=True).click()
    page.locator('#sound').click();check(page.locator('#sound').get_attribute('aria-pressed')=='true','声音开关正常响应')
    page.reload();check(page.locator('#sound').get_attribute('aria-pressed')=='true','声音偏好保存')
    # 在新浏览器会话启动前设置损坏存档，避免旧页面关闭时的自动保存覆盖夹具。
    corrupt=browser.new_context();corrupt.set_offline(True)
    corrupt.add_init_script("localStorage.setItem('crystal-lab-v2',JSON.stringify({current:2,sessions:{2:{path:['down','__proto__']}},completed:{2:{moves:'<img src=x>'}}}))")
    damaged=corrupt.new_page();damaged.on('pageerror',lambda e:errors.append(str(e)));damaged.goto(URL)
    check(damaged.locator('#moves').inner_text()=='0' and damaged.locator('#progress').inner_text()=='0 / 6 完成','非法存档安全回到合法起点')
    corrupt.close()
    broken=browser.new_context();broken.set_offline(True)
    broken.add_init_script("localStorage.setItem('crystal-lab-v2','{broken')")
    damaged=broken.new_page();damaged.on('pageerror',lambda e:errors.append(str(e)));damaged.goto(URL)
    check(damaged.locator('#level-name').inner_text()=='认识推动','损坏 JSON 不阻止启动')
    broken.close()
    context.close()
    mobile=browser.new_context(viewport={'width':390,'height':844},is_mobile=True,has_touch=True)
    mobile.set_offline(True);phone=mobile.new_page();phone.on('pageerror',lambda e:errors.append(str(e)))
    phone.goto(URL);phone.wait_for_load_state('load')
    check(phone.evaluate('document.documentElement.scrollWidth<=innerWidth'),'手机尺寸没有横向溢出')
    phone.screenshot(path=str(ROOT/'artifacts/03-mobile.png'),full_page=True)
    phone.locator('#level-select').select_option('1');phone.get_by_role('button',name='向下',exact=True).tap()
    check(phone.locator('#moves').inner_text()=='1','触屏方向按钮推动正常')
    phone.locator('#undo').tap()
    # 通过 Chrome 的真实触摸事件在棋盘滑动。
    rect=phone.locator('#board').bounding_box();x=rect['x']+rect['width']/2;y=rect['y']+rect['height']/2
    session=mobile.new_cdp_session(phone)
    session.send('Input.dispatchTouchEvent',{'type':'touchStart','touchPoints':[{'x':x,'y':y}]})
    session.send('Input.dispatchTouchEvent',{'type':'touchMove','touchPoints':[{'x':x,'y':y+60}]})
    session.send('Input.dispatchTouchEvent',{'type':'touchEnd','touchPoints':[]})
    check(phone.locator('#moves').inner_text()=='1','真实触屏滑动推动正常')
    mobile.close()
    denied=browser.new_context();denied.set_offline(True)
    denied.add_init_script("Storage.prototype.setItem=function(){throw new Error('blocked')};Storage.prototype.getItem=function(){throw new Error('blocked')}")
    blocked=denied.new_page();blocked.goto(URL);blocked.get_by_role('button',name='向右',exact=True).click()
    check(blocked.get_by_role('dialog').count()==1 and '仍可游玩' in blocked.locator('#save-note').inner_text(),'存储被拒绝时仍可正常通关')
    denied.close();browser.close()
check(not errors,'浏览器无脚本或控制台错误')
(ROOT/'artifacts/browser-report.json').write_text(json.dumps({'passed':passed,'errors':errors,'note':'Chrome 自动化离线测试；手机尺寸与触屏模拟，不是真机或真人试玩。'},ensure_ascii=False,indent=2),encoding='utf-8')
